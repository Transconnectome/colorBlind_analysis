S6P_DIR = PHASE2 / "results" / "s6p_hc_subset"
OUT_PATH = SPEARMAN_DIR / "COMPARISON_REPORT.md"

CVD_FAMILY = {'sub-08': 'deutan', 'sub-09': 'protan'}


def _safe_spearman(a, b):
    a, b = np.asarray(a, dtype=float), np.asarray(b, dtype=float)
    if np.std(a) < 1e-15 or np.std(b) < 1e-15:
        return 0.0
    rho, _ = spearmanr(a, b)
    return float(rho) if np.isfinite(rho) else 0.0


def _safe_cosine(a, b):
    val = cosine_similarity(a, b)
    return float(val) if np.isfinite(val) else 0.0


def setup_rdm_cache(subject: str, roi: str):
    """Precompute delta_rdm_obs and HC W's so we can evaluate sim ΔRDM at any δθ."""
    K = ROI_K[roi]
    cvd_amp = load_amplitudes(subject, roi)
    hc_amps = load_hc_pool(roi)
    C_baseline = create_basis_full(K, basis_type='fe')[HUE_ANGLES.astype(int)]
    delta_rdm_obs, _, _, _ = compute_delta_rdm_obs(cvd_amp, hc_amps, distance='correlation')
    hc_W, _ = precompute_hc_W(hc_amps, C_baseline)
    rdm_baseline = {h: compute_rdm_correlation(C_baseline @ W) for h, W in hc_W.items()}
    return {
        'K': K, 'C_baseline': C_baseline,
        'hc_W': hc_W, 'rdm_baseline': rdm_baseline,
        'delta_rdm_obs': delta_rdm_obs,
    }


def evaluate_at(delta_8vec, cache):
    """Return (ρ, cos) at given δθ using cached HC W's."""
    n_ch = cache['K']
    C_shifted = design_from_delta(delta_8vec, n_channels=n_ch)
    deltas = []
    for h, W in cache['hc_W'].items():
        Y = C_shifted @ W
        deltas.append(compute_rdm_correlation(Y) - cache['rdm_baseline'][h])
    sim = np.mean(deltas, axis=0)
    return _safe_spearman(sim, cache['delta_rdm_obs']), _safe_cosine(sim, cache['delta_rdm_obs'])


def load_cell_fits(cell_key, base_dir):
    fn = base_dir / f"{cell_key}_sigma21.json"
    with open(fn) as f:
        d = json.load(f)
    by_key = {}
    for fit in d['fits']:
        key = (fit['model'], fit.get('delta_lambda_source', '-'), fit['loss_target'])
        by_key[key] = fit
    return by_key, d


def build_param_str(fit):
    if fit['model'] == 'R+C':
        return f"g={fit['g_best']:.2f}"
    else:
        return f"(βs={fit['beta_s_best']:.0f}, βc={fit['beta_c_best']:.0f})"


def get_delta(fit, family):
    if fit['model'] == 'R+C':
        return forward_rc(fit['delta_lambda_nm'], fit['g_best'], family)
    else:
        return forward_2comp(fit['beta_s_best'], fit['beta_c_best'], family)


def main():
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    cells = [('sub-08', 'V1'), ('sub-08', 'V4'),
              ('sub-09', 'V1'), ('sub-09', 'V4')]

    rdm_caches = {c: setup_rdm_cache(*c) for c in cells}

    lines = []
    A = lines.append
    A("# S5 Spearman vs Cosine — Comparison Report")
    A("")
    A("**Generated by**: `scripts/s5_spearman_compare.py`  ")
    A("**Inputs**: cosine results = `results/s5_all_paths/`, "
      "Spearman results = `results/s5_spearman/`  ")
    A("**spearmanr tie handling**: `scipy.stats.spearmanr` default "
      "(`'average'`) — matches S6'.")
    A("")
    A("## Settings")
    A("")
    A("- σ = 21°, K = 6 uniform FE basis (Phase 1 baseline)")
    A("- 2-Comp grid: **asymmetric** `BS_GRID` β_s∈[0,50] step 2 × `BC_GRID` "
      "β_c∈[-50,50] step 2 = 26×51 = 1326 pts (matches S5; S6' uses symmetric "
      "[-50,50]² = 51×51).")
    A("- R+C grid: g∈[0,3] step 0.05 = 61 pts.")
    A("- C_baseline = `create_basis_full(K,'fe')[HUE_ANGLES]` (same as S5/S6').")
    A("- HC pool: V1 n=7, V4 n=6 (sub-07 V4 16-voxel dropped via load_hc_pool).")
    A("")

    # =========================================================================
    # Table 1 — L4 RDM only (cosine-best vs Spearman-best, full HC pool)
    # =========================================================================
    A("## Table 1 — L4 RDM only: cosine fit vs Spearman fit (full HC pool)")
    A("")
    A("| Cell | Model | Δλ src | cos-best params | sp-best params | ρ@cos-best | ρ@sp-best | cos@cos-best | cos@sp-best |")
    A("|---|---|---|---|---|---|---|---|---|")

    rc_dl_sources = {'sub-08': ['DPS_lit', 'Boehm_mid', 'JND_Lamb'],
                      'sub-09': ['DPS_lit', 'Boehm_low', 'JND_Lamb']}

    table1_rows = []
    for subj, roi in cells:
        key = f"{subj}_{roi}"
        cos_fits, _ = load_cell_fits(key, COSINE_DIR)
        sp_fits, _ = load_cell_fits(key, SPEARMAN_DIR)
        cache = rdm_caches[(subj, roi)]
        family = CVD_FAMILY[subj]

        # R+C × 3 Δλ
        for dl_src in rc_dl_sources[subj]:
            cos_fit = cos_fits[('R+C', dl_src, 'L4_RDM_corr')]
            sp_fit = sp_fits[('R+C', dl_src, 'L4_RDM_spearman')]
            d_cos = get_delta(cos_fit, family)
            rho_at_cos, cos_at_cos = evaluate_at(d_cos, cache)
            rho_at_sp = sp_fit['spearman_rho_best']
            cos_at_sp = sp_fit['cosine_at_best']
            row = {
                'cell': f"{subj} {roi}", 'model': 'R+C', 'dl': dl_src,
                'cos_params': build_param_str(cos_fit),
                'sp_params': build_param_str(sp_fit),
                'rho_at_cos': rho_at_cos, 'rho_at_sp': rho_at_sp,
                'cos_at_cos': cos_at_cos, 'cos_at_sp': cos_at_sp,
            }
            table1_rows.append(row)
            A(f"| {subj} {roi} | R+C | {dl_src} | {row['cos_params']} | "
              f"{row['sp_params']} | {rho_at_cos:+.3f} | {rho_at_sp:+.3f} | "
              f"{cos_at_cos:+.3f} | {cos_at_sp:+.3f} |")

        # 2-Comp
        cos_fit = cos_fits[('2-Comp', '-', 'L4_RDM_corr')]
        sp_fit = sp_fits[('2-Comp', '-', 'L4_RDM_spearman')]
        d_cos = get_delta(cos_fit, family)
        rho_at_cos, cos_at_cos = evaluate_at(d_cos, cache)
        rho_at_sp = sp_fit['spearman_rho_best']
        cos_at_sp = sp_fit['cosine_at_best']
        table1_rows.append({
            'cell': f"{subj} {roi}", 'model': '2-Comp', 'dl': '-',
            'cos_params': build_param_str(cos_fit),
            'sp_params': build_param_str(sp_fit),
            'rho_at_cos': rho_at_cos, 'rho_at_sp': rho_at_sp,
            'cos_at_cos': cos_at_cos, 'cos_at_sp': cos_at_sp,
        })
        A(f"| {subj} {roi} | 2-Comp | — | {build_param_str(cos_fit)} | "
          f"{build_param_str(sp_fit)} | {rho_at_cos:+.3f} | {rho_at_sp:+.3f} | "
          f"{cos_at_cos:+.3f} | {cos_at_sp:+.3f} |")
