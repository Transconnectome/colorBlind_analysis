"""S7 Nested LOO — robustness check on top of single-LOO S7 sprint.

The single-LOO S7 (`s7_loss_combo_subset.py`) selects and evaluates inside the
same 7-HC pool (subset resample → train/test split), so selection and evaluation
share the HC pool. This script adds an OUTER 7-fold LOO over HC and resamples
inner subsets only from the remaining 6 HC, so the outer-held-out HC is unseen
by parameter selection.

Per cell (subject × ROI):

  Outer loop: HC_i ∈ HC_SUBJS (7 folds)
    inner_pool = HC \\ {HC_i}              (size 6)
    inner_subsets = C(6, 4) = 15 subsets
    For each inner subset, fit:
      - models: R+C (3 Δλ sources for family) + 2-comp
      - losses: L_gamma, L_RDM
      - λ ∈ {0, 0.25, 0.5, 0.75, 1.0} on probe gamma_plus_RDM
    Inner CoV = parameter SD / |median| across 15 subsets.
    Median(δθ) → evaluate test L_γ on HC_i (held-out) using inner_pool as
    HC reference (Crawford-Howell-like specificity check: should be HIGH if
    fitted δθ captures real CVD axis).

  Aggregate per cell × (model × λ):
    - mean inner CoV across 7 outer folds
    - mean test L_γ across 7 outer folds
    - boundary-hit rate

Output: results/s7_nested_loo/cell_{idx:02d}_{subject}_{roi}.json
        (aggregated.json generated by post-processing script.)

CRITICAL: This is a *robustness check*. Real evaluation = Phase 3 behavioral
filter test. PI feedback (specificity / double-dipping) is only PARTIALLY
addressed: inner CoV is on a clean 6-HC pool, but the data is the same
fMRI dataset throughout.
"""

