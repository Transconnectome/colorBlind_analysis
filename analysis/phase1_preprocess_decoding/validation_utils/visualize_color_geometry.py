    amplitudes_raw, amplitudes_procrustes = load_subject_data(args.subject, args.roi)
    n_runs, n_colors, n_voxels = amplitudes_raw.shape
    print(f"✓ Loaded: {n_runs} runs, {n_colors} colors, {n_voxels} voxels")

    # Generate visualizations
    print(f"\nGenerating visualizations...")

    print("  Figure 1: Voxel-Color Amplitude Heatmaps...")
    plot_voxel_color_heatmaps(amplitudes_raw, amplitudes_procrustes, output_dir,
                              args.subject, args.roi)

    print("  Figure 2: RDM Matrices per run...")
    plot_rdm_matrices(amplitudes_raw, amplitudes_procrustes, output_dir,
                     args.subject, args.roi)

    print("  Figure 3: Color Space Embedding (MDS)...")
    plot_color_space_embedding(amplitudes_raw, amplitudes_procrustes, output_dir,
                               args.subject, args.roi)

    print("  Figure 4: Voxel Tuning Curves...")
    plot_voxel_tuning_curves(amplitudes_raw, amplitudes_procrustes, output_dir,
                            args.subject, args.roi)

    print("")
    print("="*80)
    print("✅ Visualization complete!")
