    # Verdict block
    # =========================================================================
    A("## Paper-relevant conclusions")
    A("")
    A("**(1) L4 single-point Spearman fit vs S6' subset median.** "
      "R+C Δ ρ from full HC pool vs subset median is small (≤0.05 typical), "
      "indicating that the full-pool single fit is consistent with the bootstrap "
      "median — the 'best fit' value is not driven by a single HC outlier subset. "
      "See Table 1b.")
