"""Compare S5 cosine-best (existing s5_all_paths) vs S5 Spearman-best (new s5_spearman).

For each cell × model × loss (L4/L6/L7/L8):
  - Cosine-best params + (ρ at cos-best, cos at cos-best)
  - Spearman-best params + (cos at sp-best, ρ at sp-best)
  - Δ params

Also: compare L4 single-point Spearman best (Spearman refit) vs S6' subset
distribution (median over C(7,k) for k∈{4,5,6}) for the full HC pool fit.

Outputs:
  results/s5_spearman/COMPARISON_REPORT.md
"""
